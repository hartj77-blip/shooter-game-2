// The sound engine, built on the browser's Web Audio API.
//
// Web Audio is a mixing desk made of connected boxes ("nodes"):
//
//   sound ─▶ gain ─▶ [3D panner] ─▶ sfx bus ─┐
//                                  ui bus  ─┼─▶ master ─▶ compressor ─▶ speakers
//          (gunshots also feed) ─▶ reverb ─┘
//
// A bus is a channel with its own volume knob ("Effects volume" in Settings).
// The 3D panner places a sound in the world: louder when close, in your left
// or right ear depending on where it is. The compressor stops lots of loud
// gunshots at once from distorting. The reverb gives shots a short echo; its
// "impulse response" (the sound of a room) is generated by code, not a file.
//
// Browsers refuse to make sound until you've clicked something, so the engine
// downloads the files early but only starts (unlock()) on your first click.

import { SOUNDS, soundFiles } from './sound-bank.js';

const BASE = 'assets/sounds/';
const MAX_VOICES = 40;

export function createAudio({ settings, fetchFn = globalThis.fetch?.bind(globalThis) }) {
  const raw = new Map();      // name -> ArrayBuffer (downloaded, not yet decoded)
  const buffers = new Map();  // name -> { buffer, offset }
  let ctx = null;
  let master, sfx, ui, reverbIn;
  let voices = 0;
  const lastPlayed = new Map();
  const ears = { x: 0, y: 0, z: 0 }; // where the listener is (for distance effects)

  /** Downloads every sound file. Call during loading; reports progress 0..1. */
  async function preload(onProgress = () => {}) {
    const names = soundFiles();
    let done = 0;
    await Promise.all(names.map(async (name) => {
      try {
        const res = await fetchFn(`${BASE}${name}.mp3`);
        if (res.ok) raw.set(name, await res.arrayBuffer());
      } catch {
        // Missing file: a synthesized stand-in is used instead.
      }
      onProgress(++done / names.length);
    }));
  }

  /** Starts the audio engine. Must be called from a click or key press. */
  async function unlock() {
    if (ctx) {
      if (ctx.state === 'suspended') await ctx.resume().catch(() => {});
      return;
    }
    const AC = globalThis.AudioContext ?? globalThis.webkitAudioContext;
    if (!AC) return;
    ctx = new AC();
    master = ctx.createGain();
    const comp = ctx.createDynamicsCompressor();
    comp.threshold.value = -14;
    comp.ratio.value = 6;
    master.connect(comp).connect(ctx.destination);
    sfx = ctx.createGain();
    ui = ctx.createGain();
    sfx.connect(master);
    ui.connect(master);
    const reverb = ctx.createConvolver();
    reverb.buffer = impulseResponse(1.4, 3.2);
    reverbIn = ctx.createGain();
    reverbIn.connect(reverb).connect(master);
    applyVolumes();
    await Promise.all([...raw].map(async ([name, data]) => {
      try {
        const buffer = await ctx.decodeAudioData(data.slice(0));
        buffers.set(name, { buffer, offset: leadingSilence(buffer) });
      } catch {
        // Couldn't decode: falls back to synthesis on play.
      }
    }));
  }

  function applyVolumes() {
    if (!ctx) return;
    master.gain.value = settings.masterVolume ?? 0.8;
    sfx.gain.value = settings.sfxVolume ?? 1;
    ui.gain.value = (settings.sfxVolume ?? 1) * 0.9;
  }

  /** MP3 files start with a few milliseconds of silence; skip it so shots feel instant. */
  function leadingSilence(buffer) {
    const data = buffer.getChannelData(0);
    for (let i = 0; i < data.length; i++) {
      if (Math.abs(data[i]) > 0.01) return Math.max(0, i / buffer.sampleRate - 0.002);
    }
    return 0;
  }

  // ------------------------------------------------------------ synthesized sounds

  function makeBuffer(seconds, fill) {
    const length = Math.max(1, Math.floor(seconds * ctx.sampleRate));
    const buffer = ctx.createBuffer(1, length, ctx.sampleRate);
    const d = buffer.getChannelData(0);
    for (let i = 0; i < length; i++) d[i] = fill(i / ctx.sampleRate, i);
    return buffer;
  }

  /** The "sound of a space": noise that fades away. Feeding sounds through it adds echo. */
  function impulseResponse(seconds, decay) {
    const length = Math.floor(seconds * ctx.sampleRate);
    const buffer = ctx.createBuffer(2, length, ctx.sampleRate);
    for (let c = 0; c < 2; c++) {
      const d = buffer.getChannelData(c);
      for (let i = 0; i < length; i++) d[i] = (Math.random() * 2 - 1) * Math.pow(1 - i / length, decay);
    }
    return buffer;
  }

  const tone = (f) => (t) => Math.sin(2 * Math.PI * f * t);
  const RECIPES = {
    tick: [0.05, (t) => tone(1700)(t) * Math.exp(-t * 90)],
    head: [0.09, (t) => (tone(2300)(t) + 0.6 * tone(3400)(t)) * Math.exp(-t * 45) * 0.6],
    kill: [0.16, (t) => (tone(900)(t) * Math.exp(-t * 30) + tone(1800)(t) * Math.exp(-t * 60)) * 0.7],
    beep: [0.14, (t) => tone(880)(t) * Math.min(1, (0.14 - t) * 40)],
    chime: [0.6, (t) => [660, 880, 1320].reduce((s, f, k) => s + (t > k * 0.12 ? tone(f)(t) * Math.exp(-(t - k * 0.12) * 6) : 0), 0) * 0.4],
    buzz: [0.25, (t) => Math.sign(Math.sin(2 * Math.PI * 140 * t)) * 0.4 * Math.min(1, (0.25 - t) * 20)],
    // Stand-ins for recordings that failed to load.
    shot: [0.35, (t) => ((Math.random() * 2 - 1) * Math.exp(-t * 22) + tone(55)(t) * Math.exp(-t * 18)) * 0.9],
    click: [0.04, (t) => (Math.random() * 2 - 1) * Math.exp(-t * 160)],
    ring: [0.9, (t) => (tone(1350)(t) + 0.5 * tone(2710)(t)) * Math.exp(-t * 5) * 0.6],
    thud: [0.08, (t) => (Math.random() * 2 - 1) * Math.exp(-t * 60) * 0.7],
    // A bullet passing your ear: a short hiss with a falling whistle.
    whizz: [0.2, (t) => {
      const env = Math.sin(Math.PI * Math.min(1, t / 0.2)) ** 2;
      return ((Math.random() * 2 - 1) * 0.55 + Math.sin(2 * Math.PI * (2600 - 3500 * t) * t) * 0.45) * env;
    }],
    heartbeat: [0.5, (t) => tone(52)(t) * (Math.exp(-t * 28) + (t > 0.17 ? 0.7 * Math.exp(-(t - 0.17) * 30) : 0))],
    radio: [0.1, (t) => (Math.sign(Math.sin(2 * Math.PI * 1150 * t)) * 0.25 + (Math.random() * 2 - 1) * 0.35) * Math.exp(-t * 35)],
    laser: [0.28, (t) => tone(900 + 1600 * t)(t) * Math.min(1, t * 40) * Math.min(1, (0.28 - t) * 30) * 0.5],
  };
  const fallbackFor = (name) =>
    /rifle|smg|shotgun|pistol/.test(name) && !/reload/.test(name) ? 'shot'
      : name.startsWith('ding') ? 'ring'
        : /hit_|step|land|hurt|bodyfall/.test(name) ? 'thud' : 'click';

  function bufferFor(entry, name) {
    const key = entry.synth ?? entry.files[Math.floor(Math.random() * entry.files.length)];
    if (!buffers.has(key)) {
      const recipe = RECIPES[entry.synth ?? fallbackFor(name)];
      buffers.set(key, { buffer: makeBuffer(recipe[0], recipe[1]), offset: 0 });
    }
    return buffers.get(key);
  }

  // ------------------------------------------------------------ playing

  /**
   * Plays a sound from the bank.
   * @param {string} name   key in SOUNDS
   * @param {object} [opts] { position: {x,y,z} for 3D sounds, volume, rate, delay (seconds),
   *                          spatial: place it in the world even if the bank entry doesn't (an enemy's gun) }
   */
  function play(name, opts = {}) {
    if (!ctx || ctx.state !== 'running') return;
    const entry = SOUNDS[name];
    if (!entry || voices >= MAX_VOICES) return;
    // Many identical sounds in the same instant (8 shotgun pellets) just get louder; three is plenty.
    const now = ctx.currentTime;
    const recent = lastPlayed.get(name) ?? [];
    const fresh = recent.filter((t) => now - t < 0.03);
    if (fresh.length >= 3) return;
    fresh.push(now);
    lastPlayed.set(name, fresh);

    const { buffer, offset } = bufferFor(entry, name);
    const source = ctx.createBufferSource();
    source.buffer = buffer;
    source.playbackRate.value = (opts.rate ?? 1) * (1 + (Math.random() * 2 - 1) * (entry.pitch ?? 0));
    const gain = ctx.createGain();
    gain.gain.value = entry.volume * (opts.volume ?? 1) * (0.92 + Math.random() * 0.08);
    source.connect(gain);

    let out = gain;
    if ((opts.spatial ?? entry.spatial) && opts.position) {
      // Far-away sounds lose their treble (air soaks up high notes): a distant
      // gunshot is a dull thump, a close one a sharp crack.
      const d = Math.hypot(opts.position.x - ears.x, opts.position.y - ears.y, opts.position.z - ears.z);
      if (d > 15) {
        const lp = ctx.createBiquadFilter();
        lp.type = 'lowpass';
        lp.frequency.value = Math.max(700, 18000 / (1 + (d - 15) / 10));
        out.connect(lp);
        out = lp;
      }
      const p = ctx.createPanner();
      p.panningModel = 'HRTF';
      p.distanceModel = 'inverse';
      p.refDistance = 3;
      p.rolloffFactor = 1.1;
      p.maxDistance = 120;
      setPosition(p, opts.position);
      out.connect(p);
      out = p;
    }
    out.connect(entry.bus === 'ui' ? ui : sfx);
    if (entry.reverb) {
      const send = ctx.createGain();
      send.gain.value = entry.reverb;
      gain.connect(send).connect(reverbIn);
    }
    voices++;
    source.onended = () => {
      voices--;
      source.disconnect();
    };
    source.start(now + (opts.delay ?? 0), offset);
  }

  function setPosition(node, p) {
    if (node.positionX) {
      node.positionX.value = p.x;
      node.positionY.value = p.y;
      node.positionZ.value = p.z;
    } else {
      node.setPosition(p.x, p.y, p.z);
    }
  }

  /** Puts your ears where the camera is, pointing where it looks. */
  function update(camera) {
    if (!ctx) return;
    const l = ctx.listener;
    const e = camera.matrixWorld.elements;
    const fwd = [-e[8], -e[9], -e[10]];
    const up = [e[4], e[5], e[6]];
    const pos = camera.position;
    ears.x = pos.x; ears.y = pos.y; ears.z = pos.z;
    if (l.positionX) {
      l.positionX.value = pos.x; l.positionY.value = pos.y; l.positionZ.value = pos.z;
      l.forwardX.value = fwd[0]; l.forwardY.value = fwd[1]; l.forwardZ.value = fwd[2];
      l.upX.value = up[0]; l.upY.value = up[1]; l.upZ.value = up[2];
    } else {
      l.setPosition(pos.x, pos.y, pos.z);
      l.setOrientation(...fwd, ...up);
    }
  }

  return {
    preload,
    unlock,
    play,
    update,
    applyVolumes,
    get ready() { return !!ctx && ctx.state === 'running'; },
  };
}
